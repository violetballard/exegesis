def validate_patch_review_state_consistency(
    state: "PatchReviewState | dict",
    outcome: "EngineLoopOutcome | dict",
) -> None:
    """Assert that a PatchReviewState and an EngineLoopOutcome reference the same patch and agree on resolution.

    Module-level convenience wrapper for ``PatchReviewState.validate_consistency_with_outcome``.
    Accepts either a typed ``PatchReviewState`` or the dict produced by
    ``advance_patch_review_state``.  Raises ``ValueError`` on any inconsistency.
    """
    from exegesis_shared.models.patch_review_state import PatchReviewState
    if isinstance(state, dict):
        state = PatchReviewState.from_dict(state)
    elif not isinstance(state, PatchReviewState):
        raise TypeError("state must be a PatchReviewState or a dict")
    state.validate_consistency_with_outcome(outcome)


